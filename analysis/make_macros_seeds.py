#!/usr/bin/env python3
"""Macros of the seed repeats of the preference stage: three trainings that differ in the seed only, each evaluated
on the 324-task subset with the candidate list.

  usage: make_macros_seeds.py SUBSET_IDS.json SEED1.jsonl SEED2.jsonl SEED3.jsonl OUT.tex OUT.json

Rules imported from analysis/make_macros.py: completion with the 95 % task-level bootstrap of the subsets. Also
written: the lowest and highest completion of the three, and the number of tasks whose verdict is not the same in
all three runs. Stops on a wrong task set or an unscored row.
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_macros as mm

ids = json.load(open(sys.argv[1], encoding='utf-8'))
if len(ids) != 324 or len(set(ids)) != 324:
    mm.fail('the subset does not hold 324 distinct tasks')
files, out_tex, out_json = sys.argv[2:5], sys.argv[5], sys.argv[6]
o = mm.Out(); o.section(8, 'Seed repeats of the preference stage on the 324-task subset')
S, D = [], []
for tok, f in zip(('One', 'Two', 'Three'), files):
    rows = mm.read_per_task(f, ids, f'preference stage, seed {tok.lower()}, 324-task subset')
    s = mm.summary(rows, ids, None, cluster=False, ci='boot')
    mm.put_summary(o, f'PmSeed{tok}', s, f'preference stage, seed {tok.lower()}, 324-task subset with the candidate list', '95 % task-level bootstrap')
    S.append(s); D.append({t: bool(mm.done(rows[t])) for t in ids})
    print(f'seed {tok.lower()}: {s["done"]}/{s["n"]} = {s["comp"]:.3f} [{s["lo"]:.3f}, {s["hi"]:.3f}]')
lo, hi = min(S, key=lambda s: s['comp']), max(S, key=lambda s: s['comp'])
o.put('PmSeedCompMin', mm.num(lo['comp']), lo['comp'], 'lowest completion of the three seeds')
o.put('PmSeedCompMax', mm.num(hi['comp']), hi['comp'], 'highest completion of the three seeds')
o.put('PmSeedDoneMin', mm.thou(lo['done']), lo['done'], 'fewest tasks completed among the three seeds')
o.put('PmSeedDoneMax', mm.thou(hi['done']), hi['done'], 'most tasks completed among the three seeds')
mixed = sum(1 for t in ids if len({d[t] for d in D}) > 1)
o.put('PmSeedMixedTasks', mm.thou(mixed), mixed, 'tasks whose verdict is not the same under all three seeds')
o.put('PmSeedMixedPct', mm.pct1(mixed, len(ids)), mixed / len(ids), 'the same as a percentage of the 324 tasks')
print(f'range {lo["done"]} to {hi["done"]} of 324; tasks with differing verdicts {mixed}')
lines = ['% Generated by analysis/make_macros_seeds.py (seed repeats of the preference stage).']
lines += [l.split('  % ')[0] for l in o.lines if l.startswith('\\newcommand')]
open(out_tex, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
json.dump(o.vals, open(out_json, 'w', encoding='utf-8'), indent=1)
print(f'{len(lines) - 1} macros -> {out_tex}')
