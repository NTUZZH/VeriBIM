#!/usr/bin/env python3
"""Macros of the run-to-run stability of the proposed model, from the outputs of flip_rate.py.

  usage: make_macros_flip.py FLIP_324.json FLIP_108.json OUT.tex
"""
import json, sys

def block(stem, d):
    n, f = d["n"], d["flips"]
    assert 0 <= f <= n and d["completed_a"] <= n and d["completed_b"] <= n
    return [f"\\newcommand{{\\PmFlip{stem}N}}{{{n}}}",
            f"\\newcommand{{\\PmFlip{stem}Count}}{{{f}}}",
            f"\\newcommand{{\\PmFlip{stem}Pct}}{{{100 * f / n:.1f}}}",
            f"\\newcommand{{\\PmFlip{stem}DoneBench}}{{{d['completed_a']}}}",
            f"\\newcommand{{\\PmFlip{stem}DoneSeparate}}{{{d['completed_b']}}}"]

a, b = json.load(open(sys.argv[1])), json.load(open(sys.argv[2]))
lines = ["% Generated by analysis/make_macros_flip.py from the outputs of analysis/flip_rate.py (two runs of the proposed model under identical settings)."]
lines += block("ThreeTwentyFour", a) + block("HundredEight", b)
open(sys.argv[3], "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("\n".join(lines[1:]))
