#!/usr/bin/env python3
"""Table rows of the proposed model without the candidate list on the two subsets (Supplementary Material).

  usage: make_macros_nolist_rows.py CONFIG.json WITH108 WITHOUT108 WITH324 WITHOUT324 GATE108.jsonl OUT.tex OUT.json

Adds to analysis/make_macros_nolist_subsets.py (completion, mean score and the task-level paired difference) the
remaining cells of the rows in Tables tab:mainfull and tab:main324: completion on the fully specified tasks, the count
of under-specified tasks answered with a request, the mean number of tool rounds (make_macros.table_row), the
building-level bootstrap interval of "with the list minus without it" (make_macros.paired, cluster=True), and on the
108-task subset the completion under the relation-gated verdict (summarize() of the gate scripts, the function behind
Table tab:gateall). WITH* and WITHOUT* are per-task files of the same model on the same subset; GATE108 holds the gate
results of the completed tasks of WITHOUT108. Stops on a wrong task set, an unscored row or a gate row with an error.

Also the paired difference of the run without the list against each commercial arm with the library note on the
108-task subset, and against Claude Sonnet 5.5 with the library note on the 324-task subset (make_macros.paired).
"""
import json, os, sys
from pathlib import Path
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_macros as mm

cfg = json.load(open(sys.argv[1], encoding='utf-8'))
w108, n108, w324, n324, gate108, out_tex, out_json = sys.argv[2:9]
C = mm.Ctx(cfg)
M, V = ['% GENERATED by analysis/make_macros_nolist_rows.py; do not edit by hand.'], {}


def put(name, shown, val, src):
    V[name] = val
    M.append(f'\\newcommand{{\\{name}}}{{{shown}}}  % {src}')


for tok, ids, fw, fn in (('HundredEight', C.S108, w108, n108), ('ThreeTwentyFour', C.S324, w324, n324)):
    with_ = mm.read_per_task(fw, ids, f'{tok} subset, with the candidate list')
    without = mm.read_per_task(fn, ids, f'{tok} subset, without the candidate list')
    r = mm.table_row(without, ids, C)
    src = os.path.basename(os.path.dirname(fn)) + '/' + os.path.basename(fn)
    put(f'Pm{tok}NoListFullComp', mm.num(r['full']), r['full'], src + f', fully specified tasks ({r["n_full"]})')
    put(f'Pm{tok}NoListUnderDone', r['under'], r['under'], src + ', under-specified tasks answered with a request')
    put(f'Pm{tok}NoListUnderN', r['n_under'], r['n_under'], src + ', under-specified tasks')
    put(f'Pm{tok}NoListRounds', mm.f2(r['rounds']), r['rounds'], src + ', mean tool rounds per task')
    P = mm.paired(with_, without, ids, C, cluster=True)
    lo_, hi_ = mm.bounds(P['clo'], P['chi'])
    put(f'Pm{tok}ListMinusNoListCLo', lo_, P['clo'], 'with minus without the list, 95 % building-level bootstrap, lower')
    put(f'Pm{tok}ListMinusNoListCHi', hi_, P['chi'], 'with minus without the list, 95 % building-level bootstrap, upper')
    V[f'check_{tok}'] = {'all': r['all'], 'mean': r['mean'], 'diff': P['diff'], 'b': P['b'], 'c': P['c'], 'p': P['p']}
    # the run without the list against the commercial arms with the library note (the same added input)
    arms = {x['key']: x for x in cfg['arms']['sub108' if tok == 'HundredEight' else 'sub324']}
    for k in (('GptNote', 'DeepSeekNote', 'SonnetNote', 'GeminiNote') if tok == 'HundredEight' else ('SonnetNote',)):
        other = mm.read_per_task(arms[k]['path'], ids, f'{tok} subset, {k}')
        Q = mm.paired(without, other, ids, C, cluster=True)
        o = mm.Out()
        mm.put_paired(o, f'Pm{tok}NoListMinus{k}', Q, f'{tok} subset, proposed model without the list minus {k}', tango_=False, counts=False)
        for l in o.lines:
            if l.startswith('\\newcommand'):
                M.append(l)
        V.update(o.vals)
        V[f'check_{tok}_{k}'] = {'diff': Q['diff'], 'b': Q['b'], 'c': Q['c'], 'p': Q['p']}
    if tok == 'HundredEight':
        sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'gate'))
        import gate_summary as S
        gate = S.load_jsonl(gate108)
        s, lost, _ = S.summarize('sub108_nolist', without, gate)
        for key in ('completed_rows_missing', 'rows_with_error', 'completed_flag_mismatch'):
            if s[key]:
                mm.fail(f'gate results of the 108-task run without the list: {key} {s[key][:5]} ({len(s[key])} rows)')
        if s['completed'] != sum(int(mm.done(without[t])) for t in ids):
            mm.fail('gate summary and the per-task file disagree on the completed count')
        put('PmHundredEightNoListGateAfter', s['completed_gated'], s['completed_gated'], 'completed and relation gate passed')
        put('PmHundredEightNoListGateAfterComp', mm.num(s['completed_gated'] / len(ids)), s['completed_gated'] / len(ids), 'of 108')
        put('PmHundredEightNoListGateLost', s['removed_by_gate'], s['removed_by_gate'], 'completions removed by the relation gate')
        V['gate_lost_108'] = [{k: x[k] for k in x if k != 'arm'} for x in lost]
open(out_tex, 'w', encoding='utf-8').write('\n'.join(M) + '\n')
json.dump(V, open(out_json, 'w', encoding='utf-8'), indent=1, default=str)
print(f'{len(M) - 1} macros -> {out_tex}')
print(json.dumps({k: v for k, v in V.items() if k.startswith('check_') or k.startswith('gate_lost')}, default=str))
