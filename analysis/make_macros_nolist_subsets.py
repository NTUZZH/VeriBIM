#!/usr/bin/env python3
"""Macros of the proposed model without the candidate list on the 108-task and 324-task subsets.

  usage: make_macros_nolist_subsets.py --with108 F --without108 F --with324 F --without324 F
                                       --subset108 IDS.json --subset324 IDS.json --out-tex OUT.tex --out-json OUT.json

Each F is a per-task file of the same model on the same subset, with or without the candidate list. The rules are
those of analysis/make_macros.py, imported from it: completion with the 95 % task-level bootstrap interval of the
subsets (summary), and the paired difference "with the list minus without it" with its task-level bootstrap interval,
Tango interval, discordant counts and exact McNemar p (paired). Stops on a wrong task set or an unscored row.
"""
import argparse, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_macros as mm

ap = argparse.ArgumentParser()
for a in ('--with108', '--without108', '--with324', '--without324', '--subset108', '--subset324', '--out-tex', '--out-json'):
    ap.add_argument(a, required=True)
a = ap.parse_args()
o = mm.Out()
o.section(6, 'The candidate list on the two subsets: proposed model with and without the list')
for tok, n, fw, fn, fs in (('HundredEight', 108, a.with108, a.without108, a.subset108),
                           ('ThreeTwentyFour', 324, a.with324, a.without324, a.subset324)):
    ids = json.load(open(fs, encoding='utf-8'))
    if len(ids) != n or len(set(ids)) != n:
        mm.fail(f'{fs}: {len(ids)} ids, wanted {n} distinct')
    with_ = mm.read_per_task(fw, ids, f'{tok} subset, proposed model with the candidate list')
    without = mm.read_per_task(fn, ids, f'{tok} subset, proposed model without the candidate list')
    src = f'{tok} subset, proposed model without the candidate list'
    s = mm.summary(without, ids, None, cluster=False, ci='boot')
    mm.put_summary(o, f'Pm{tok}NoList', s, src, '95 % task-level bootstrap')
    P = mm.paired(with_, without, ids, None, cluster=False)
    mm.put_paired(o, f'Pm{tok}ListMinusNoList', P, f'{tok} subset, proposed model with minus without the candidate list')
    print(f'{tok}: without the list {s["done"]}/{s["n"]} = {s["comp"]:.3f} [{s["lo"]:.3f}, {s["hi"]:.3f}]; with the list '
          f'{P["a_done"]}; with minus without {P["diff"]:+.3f} [{P["lo"]:+.3f}, {P["hi"]:+.3f}], only with {P["b"]}, '
          f'only without {P["c"]}, exact p {P["p"]:.4f}')
lines = ['% Generated by analysis/make_macros_nolist_subsets.py (proposed model without the candidate list, two subsets).']
lines += [l.split('  % ')[0] for l in o.lines if l.startswith('\\newcommand')]
open(a.out_tex, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
json.dump(o.vals, open(a.out_json, 'w', encoding='utf-8'), indent=1)
print(f'{len(lines) - 1} macros -> {a.out_tex}')
