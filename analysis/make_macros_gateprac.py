#!/usr/bin/env python3
"""Relation-gated verdict and 1 cm tolerance on the practitioners' requests, proposed model (Supplementary Material).

  usage: make_macros_gateprac.py OUT.tex OUT.json

Reads the per-request rows of the proposed model's run with the candidate list (arm prac_200 of
analysis/gate/gate_summary.py) and the gate results of the
completed requests (results/relation_gate/gate_prac_200.jsonl). The counting is summarize() of analysis/gate/gate_summary.py, which is the function behind the other rows of Table tab:gateall: relation-gated = completed and gate_pass;
1 cm = completed and every paired target within 0.01 m in centre and in every dimension; both = the intersection.
Stops when a completed request has no gate row, when a gate row carries an error, or when the counts disagree with the
installed macros of the same run.
"""
import json, re, sys
from pathlib import Path

G = Path('results/relation_gate')
sys.path.insert(0, str(Path(__file__).resolve().parent / 'gate'))
import gate_summary as S        # noqa: E402
C = S

ARM = 'prac_200'
out_tex, out_json = sys.argv[1], sys.argv[2]
rows = C.per_task_rows(ARM)
gate = S.load_jsonl(G / f'gate_{ARM}.jsonl')
s, lost, lost_cm = S.summarize(ARM, rows, gate)
n = len(rows)
if n != 200:
    sys.exit(f'{n} rows, wanted the 200 requests')
for key in ('completed_rows_missing', 'rows_with_error', 'completed_flag_mismatch'):
    if s[key]:
        sys.exit(f'{key}: {s[key][:5]} ({len(s[key])} rows)')
# cross-check with the installed macros of the same run
inst = open('analysis_out/macros_pm_main.tex', encoding='utf-8').read()   # written by analysis/make_macros.py
m = re.search(r'\\newcommand\{\\PmPracDone\}\{([0-9,]+)\}', inst)
if not m or int(m.group(1).replace(',', '')) != s['completed']:
    sys.exit(f'completed here {s["completed"]}, installed PmPracDone {m.group(1) if m else None}')
V = {'n': n, 'completed': s['completed'], 'gated': s['completed_gated'], 'cm': s['completed_1cm'],
     'both': s['completed_gated_and_1cm'], 'removed_by_gate': s['removed_by_gate'], 'removed_by_1cm': s['removed_by_1cm'],
     'removed_by_gate_by_class': s.get('removed_by_gate_by_class'), 'lost_gate': lost, 'lost_1cm': lost_cm}
M = ['% GENERATED by analysis/make_macros_gateprac.py; do not edit by hand.',
     f'% inputs: per-request rows of arm {ARM} and results/relation_gate/gate_{ARM}.jsonl ({len(gate)} rows)']


def put(name, shown, src):
    M.append(f'\\newcommand{{\\{name}}}{{{shown}}}  % {src}')


put('PmPracGateAfter', s['completed_gated'], 'completed and relation gate passed')
put('PmPracGateAfterComp', f"{s['completed_gated'] / n:.3f}", 'of 200')
put('PmPracGateLost', s['removed_by_gate'], 'completions removed by the relation gate')
put('PmPracAbsDoneCm', s['completed_1cm'], 'completed and every paired target within 1 cm')
put('PmPracAbsCompCm', f"{s['completed_1cm'] / n:.3f}", 'of 200')
put('PmPracAbsCmLost', s['removed_by_1cm'], 'completions removed by the 1 cm tolerance')
put('PmPracGateBoth', s['completed_gated_and_1cm'], 'completed under both')
put('PmPracGateBothComp', f"{s['completed_gated_and_1cm'] / n:.3f}", 'of 200')
open(out_tex, 'w', encoding='utf-8').write('\n'.join(M) + '\n')
json.dump(V, open(out_json, 'w', encoding='utf-8'), indent=1, default=str)
print(json.dumps({k: v for k, v in V.items() if not k.startswith('lost')}))
for x in lost:
    print('lost under gate:', {k: x[k] for k in x if k != 'arm'})
for x in lost_cm:
    print('lost under 1 cm:', {k: x[k] for k in x if k != 'arm'})
