#!/usr/bin/env python3
"""Cost and yield of task generation, from the funnel files that the generator writes (Supplementary Material).

  usage: make_macros_genfunnel.py OUT.tex OUT.json

Reads results/generation_funnel/*/funnel.json, the twelve generation runs of generator release 0.9.0 (training tasks
in IFC4, IFC4X3 and the IFC2X3 student files, the top-up runs, and the benchmark candidates in the three versions).
Each file records the sampled tasks (n_attempted), the tasks that passed every validity check (n_accepted), the
processor time of the run (cpu_seconds, CPU time and not wall-clock time) and the rejections by stage.
Outputs: totals, the share accepted, CPU-seconds per accepted task, CPU-hours, and the number of sampled tasks that
were rejected after the ground truth had been built (stages parse, apply, self_score, batch_scope, meshable).
Stops when a file is missing a field or comes from another generator release.
"""
import glob, json, sys
G = 'results/generation_funnel'
files = sorted(glob.glob(f'{G}/*/funnel.json'))
if len(files) != 12:
    sys.exit(f'{len(files)} funnel files, wanted 12')
att = acc = 0; cpu = 0.0; late = 0; runs = []
for f in files:
    d = json.load(open(f))
    if d.get('generator_version') != 'veribim-gen/0.9.0':
        sys.exit(f'{f}: generator {d.get("generator_version")}')
    for k in ('n_attempted', 'n_accepted', 'cpu_seconds', 'stages'):
        if k not in d:
            sys.exit(f'{f}: no {k}')
    if not (0 < d['n_accepted'] <= d['n_attempted']) or d['cpu_seconds'] <= 0:
        sys.exit(f'{f}: implausible counts')
    att += d['n_attempted']; acc += d['n_accepted']; cpu += d['cpu_seconds']
    late += sum(v for k, v in d['stages'].items() if k in ('parse', 'apply', 'self_score', 'batch_scope', 'meshable'))
    runs.append({'run': f.split('/')[-2], 'attempted': d['n_attempted'], 'accepted': d['n_accepted'], 'cpu_seconds': d['cpu_seconds']})
V = {'runs': runs, 'attempted': att, 'accepted': acc, 'cpu_seconds': cpu, 'rejected_after_ground_truth': late}
M = ['% GENERATED by analysis/make_macros_genfunnel.py; do not edit by hand.',
     '% inputs: results/generation_funnel/*/funnel.json (12 generation runs of generator release 0.9.0)']


def put(name, shown, src):
    M.append(f'\\newcommand{{\\{name}}}{{{shown}}}  % {src}')


put('GenFunnelRuns', 'twelve', 'generation runs')
put('GenFunnelAttempted', f'{att:,}', 'sampled tasks')
put('GenFunnelAccepted', f'{acc:,}', 'tasks that passed every validity check')
put('GenFunnelAcceptPct', f'{100 * acc / att:.1f}', 'accepted over sampled, percent')
put('GenFunnelCpuSecPerTask', f'{cpu / acc:.1f}', 'CPU-seconds per accepted task')
put('GenFunnelCpuHours', f'{cpu / 3600:.0f}', 'CPU-hours of the twelve runs')
put('GenFunnelLateRejected', f'{late:,}', 'sampled tasks rejected after the ground truth was built')
open(sys.argv[1], 'w', encoding='utf-8').write('\n'.join(M) + '\n')
json.dump(V, open(sys.argv[2], 'w'), indent=1)
print(json.dumps({k: v for k, v in V.items() if k != 'runs'}))
