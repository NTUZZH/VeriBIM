#!/usr/bin/env python3
"""Reported model behind the chat template of training against the reported runs (Supplementary Material).

  usage: make_macros_tplcheck.py OUT.tex OUT.json

Reads results/template_check/compare_{sub108,rw,prac}.json, which analysis/compare_runs.py wrote
from the per-task files of the reported runs (chat template of the base model, run a) and of the same model, inputs and
flags behind the chat template of training (run b). Stops when a count of run a differs from the macro of the reported run that analysis/make_macros.py
wrote.
"""
import json, os, re, sys
D = os.environ.get('VERIBIM_TPLCHECK_DIR', 'results/template_check')
INST = open('analysis_out/macros_pm_main.tex', encoding='utf-8').read()   # written by analysis/make_macros.py


def installed(name):
    m = re.search(r'\\newcommand\{\\' + name + r'\}\{([0-9,]+)\}', INST)
    return int(m.group(1).replace(',', '')) if m else None


V, M = {}, ['% GENERATED by analysis/make_macros_tplcheck.py; do not edit by hand.',
            '% inputs: results/template_check/compare_{sub108,rw,prac}.json']
ps = []
for key, tok, n, ref in (('sub108', 'HundredEight', 108, 'PmHundredEightDone'), ('rw', 'Rw', 172, 'PmRwDone'), ('prac', 'Prac', 200, 'PmPracDone')):
    d = json.load(open(f'{D}/compare_{key}.json'))
    if d['n'] != n:
        sys.exit(f'{key}: n {d["n"]}, wanted {n}')
    have = installed(ref)
    if have is not None and have != d['stock_template']:
        sys.exit(f'{key}: run a completes {d["stock_template"]}, installed {ref} is {have}')
    V[key] = {k: d[k] for k in ('n', 'stock_template', 'training_template', 'only_stock_template', 'only_training_template', 'verdict_changes', 'difference_b_minus_a', 'interval95', 'mcnemar_exact_p')}
    V[key]['installed_macro_checked'] = ref if have is not None else None
    M.append(f'\\newcommand{{\\PmTplStock{tok}Done}}{{{d["stock_template"]}}}  % reported run, chat template of the base model')
    M.append(f'\\newcommand{{\\PmTpl{tok}Done}}{{{d["training_template"]}}}  % same model behind the chat template of training')
    M.append(f'\\newcommand{{\\PmTpl{tok}Changes}}{{{d["verdict_changes"]}}}  % tasks whose verdict differs between the two runs')
    ps.append(d['mcnemar_exact_p'])
M.append(f'\\newcommand{{\\PmTplMinP}}{{{min(ps):.2f}}}  % smallest exact McNemar p of the three comparisons')
V['min_p'] = min(ps)
open(sys.argv[1], 'w', encoding='utf-8').write('\n'.join(M) + '\n')
json.dump(V, open(sys.argv[2], 'w'), indent=1)
print(json.dumps(V)[:700])
