#!/usr/bin/env python3
"""Which helper-library functions the library note names, and whether the tasks that need an unnamed one explain a gap.

  usage: note_coverage.py OUT.json OUT.tex

The library exports len(__all__) functions; the note that the library-note arms receive names a part of them.
A task "uses an unnamed function" when the reported model's own transcript on that task calls an exported function
that the note does not name (the model-independent alternative, the edit kind, is printed next to it).
Per arm on the 108-task subset: completion on the tasks that use an unnamed function and on the other tasks,
and the number of tasks on which the arm itself called an unnamed function.
"""
import ast, collections, json, re, sys, os, glob
P = '.'
sys.path.insert(0, f'{P}/analysis')
import make_macros as mm

src = open(f'{P}/code/harness/modifc_harness/veribim_geom.py', encoding='utf-8').read()
exported = []
for n in ast.parse(src).body:
    if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == '__all__' for t in n.targets):
        exported += [c.value for c in ast.walk(n.value) if isinstance(c, ast.Constant) and isinstance(c.value, str)]
note = open(f'{P}/provenance/library_note.txt', encoding='utf-8').read()
named = {a for a in exported if re.search(r'\bgeom\.' + re.escape(a) + r'\b', note)}   # named as a function of the library
unnamed = sorted(set(exported) - named)
cfg = json.load(open(f'{P}/analysis/config.json'))
ids = json.load(open(cfg['tasks']['subset108']))
ids = ids if isinstance(ids, list) else ids.get('task_ids') or ids.get('ids')
tasks = {}
for l in open(cfg['tasks']['benchmark']):
    if l.strip():
        t = json.loads(l); tasks[t['task_id']] = t
assert len(ids) == 108 and all(i in tasks for i in ids)
full = [i for i in ids if tasks[i]['edit_kind'] != 'clarify' and not tasks[i].get('clarification')]


def calls(tdir, tid):
    f = os.path.join(tdir, tid + '.json')
    if not os.path.exists(f):
        return None
    o = json.load(open(f, encoding='utf-8'))
    code = []
    for m in o.get('messages', []):
        if m.get('role') != 'assistant':
            continue
        tc = m.get('tool_calls') or []
        if isinstance(tc, str):
            code.append(tc)
        else:
            for c in tc:
                code.append(json.dumps(c))
    txt = '\n'.join(code)
    return {a for a in exported if re.search(r'\bgeom\.' + re.escape(a) + r'\b', txt)}


ARMS = {'proposed': (f'{P}/runs_local/stage_c_v14/gates/sub108/per_task_grpo_v14_c20.jsonl', f'{P}/runs_local/stage_c_v14/gates/sub108/grpo_v14_c20/transcripts')}
for a in cfg['arms']['sub108']:
    if a['key'] in ('GptNote', 'DeepSeekNote', 'SonnetNote', 'GeminiNote', 'BaseNote', 'SonnetDoc', 'SonnetAsk') and a.get('path'):
        d = os.path.join(os.path.dirname(a['path']), os.path.basename(a['path'])[len('per_task_'):-len('.jsonl')], 'transcripts')
        ARMS[a['key']] = (a['path'], d)
out = {'exported': len(exported), 'named_in_note': len(named), 'unnamed': unnamed}
own = {i: calls(ARMS['proposed'][1], i) for i in ids}
assert all(v is not None for v in own.values()), 'a transcript of the reported model is missing'
U = [i for i in full if own[i] & set(unnamed)]
N = [i for i in full if not (own[i] & set(unnamed))]
by_kind = collections.defaultdict(lambda: [0, 0, collections.Counter()])
for i in full:
    k = tasks[i]['edit_kind']; by_kind[k][0] += 1
    if own[i] & set(unnamed):
        by_kind[k][1] += 1; by_kind[k][2].update(own[i] & set(unnamed))
out['fully_specified'] = len(full); out['tasks_using_unnamed'] = len(U); out['tasks_other'] = len(N)
out['by_kind'] = {k: {'n': v[0], 'uses_unnamed': v[1], 'which': dict(v[2])} for k, v in sorted(by_kind.items())}
print(json.dumps({k: out[k] for k in ('exported', 'named_in_note', 'unnamed', 'fully_specified', 'tasks_using_unnamed', 'tasks_other')}))
for k, v in out['by_kind'].items():
    print(f'  {k:32s} n={v["n"]:2d} uses unnamed={v["uses_unnamed"]:2d} {v["which"]}')
out['arms'] = {}
for key, (pt, tdir) in ARMS.items():
    rows = mm.read_per_task(pt, ids, key)
    dU = sum(int(mm.done(rows[i])) for i in U); dN = sum(int(mm.done(rows[i])) for i in N)
    have = os.path.isdir(tdir)
    called = sum(1 for i in U if have and (calls(tdir, i) or set()) & set(unnamed)) if have else None
    out['arms'][key] = {'U_done': dU, 'U_n': len(U), 'N_done': dN, 'N_n': len(N), 'arm_called_unnamed_on_U': called, 'transcripts': have}
    print(f'{key:14s} uses-unnamed tasks {dU:2d}/{len(U)} = {dU / max(1, len(U)):.3f} | other tasks {dN:2d}/{len(N)} = {dN / max(1, len(N)):.3f} | arm itself called an unnamed function on {called} of {len(U)}')
json.dump(out, open(sys.argv[1], 'w'), indent=1)
A = out['arms']; com = ('GptNote', 'DeepSeekNote', 'SonnetNote', 'GeminiNote')
num = lambda d, n: f'{d / n:.3f}'
M = ['% GENERATED by note_coverage/note_coverage.py; do not edit by hand.',
     '% inputs: the library note of the library-note arms, the export list of the helper library, transcripts and per-task rows of the 108-task subset']
def put(name, shown, src):
    M.append(f'\\newcommand{{\\{name}}}{{{shown}}}  % {src}')
put('NoteNamedFunctions', len(named), 'exported functions that the note names as geom.<name>')
put('NoteUnnamedFunctions', len(unnamed), 'exported functions that the note does not name')
put('NoteFullTasks', len(full), 'fully specified tasks of the 108-task subset')
put('NoteUnnamedTasks', len(U), 'of them, tasks on which the reported model calls a function the note does not name')
put('NoteOtherTasks', len(N), 'the other fully specified tasks')
put('NoteOursUnnamedDone', A['proposed']['U_done'], 'reported model, completed among the first group')
put('NoteOursOtherDone', A['proposed']['N_done'], 'reported model, completed among the second group')
put('NoteSonnetUnnamedDone', A['SonnetNote']['U_done'], 'Claude Sonnet 5.5 with the library note, first group')
put('NoteSonnetOtherDone', A['SonnetNote']['N_done'], 'Claude Sonnet 5.5 with the library note, second group')
put('NoteUnnamedCompLo', num(min(A[k]['U_done'] for k in com), len(U)), 'four commercial models with the note, first group, lowest completion')
put('NoteUnnamedCompHi', num(max(A[k]['U_done'] for k in com), len(U)), 'highest')
put('NoteOtherCompLo', num(min(A[k]['N_done'] for k in com), len(N)), 'four commercial models with the note, second group, lowest completion')
put('NoteOtherCompHi', num(max(A[k]['N_done'] for k in com), len(N)), 'highest')
put('NoteOursOtherComp', num(A['proposed']['N_done'], len(N)), 'reported model, second group')
open(sys.argv[2], 'w', encoding='utf-8').write('\n'.join(M) + '\n')
