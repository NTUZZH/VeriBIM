#!/usr/bin/env python3
"""Stored true north of the benchmark files against the model's +Y axis (Supplementary Material).

  usage: make_macros_north.py OUT.tex OUT.json

Reads every model of the benchmark registry (runs_local/corpus_v10/migrator_v2/pool_bench_v10_all.json) and the
TrueNorth of its geometric representation contexts. A file counts as rotated when a stored TrueNorth is more than
0.01 degrees away from +Y. Counts the benchmark tasks, the reworded tasks and the practitioners' requests whose input
file is rotated, and how many of their instructions contain a compass word. No instruction text is written anywhere.
"""
import collections, json, math, os, re, sys
import ifcopenshell
ROOT = '.'
POOL = f'{ROOT}/runs_local/corpus_v10/migrator_v2/pool_bench_v10_all.json'
SETS = {'Bench': f'{ROOT}/runs_local/bench_v4/tasks.v4d.jsonl',
        'Rw': f'{ROOT}/round4/reword_bench/tasks_bench_rw.jsonl',
        'Prac': f'{ROOT}/practitioner_requests/results/rewrite_tasks.jsonl'}
EXPECT = {'Bench': 2100, 'Rw': 172, 'Prac': 200}
WORDS = re.compile(r'\b(north|south|east|west)', re.I)
out_tex, out_json = sys.argv[1], sys.argv[2]
pool = json.load(open(POOL))
rot, angles, state = set(), {}, collections.Counter()
for m in pool['models']:
    f = ifcopenshell.open(os.path.join(ROOT, m['relpath']))
    a = []
    for c in f.by_type('IfcGeometricRepresentationContext', include_subtypes=False):
        tn = getattr(c, 'TrueNorth', None)
        if tn is not None:
            r = list(tn.DirectionRatios)[:2]; a.append(round(math.degrees(math.atan2(r[0], r[1])), 2))
    if any(abs(x) >= 0.01 for x in a):
        rot.add(os.path.basename(m['relpath'])); angles[os.path.basename(m['relpath'])] = sorted(set(a)); state['rotated'] += 1
    else:
        state['stored along +Y' if a else 'none stored'] += 1
rot_buildings = sorted({m['building_id'] for m in pool['models'] if os.path.basename(m['relpath']) in rot})
names = [os.path.basename(m['relpath']) for m in pool['models']]
assert len(names) == len(set(names)), 'file names of the registry are not unique'
V = {'files': len(pool['models']), 'state': dict(state), 'rotated_files': sorted(rot), 'angles_deg_clockwise_from_plus_y': angles,
     'rotated_buildings': rot_buildings}
M = ['% GENERATED by analysis/make_macros_north.py; do not edit by hand.',
     '% inputs: benchmark registry pool_bench_v10_all.json and the three task files of the test (counts only)']
def put(name, val, src):
    V[name] = val; M.append(f'\\newcommand{{\\{name}}}{{{val}}}  % {src}')
put('NorthBenchFiles', len(pool['models']), 'model files of the benchmark buildings')
put('NorthRotFiles', len(rot), 'files whose stored true north is away from +Y')
put('NorthRotBuildings', len(rot_buildings), 'buildings of these files')
assert len({tuple(v) for v in angles.values()}) == 1
put('NorthRotDegrees', f"{abs(list(angles.values())[0][0]):.0f}", 'angle between the stored true north and +Y, degrees')
for key, p in SETS.items():
    rows = [json.loads(l) for l in open(p, encoding='utf-8') if l.strip()]
    assert len(rows) == EXPECT[key], (key, len(rows))
    hit = [r for r in rows if os.path.basename(str(r.get('input_ifc') or '')) in rot]
    def text(r):
        if key == 'Prac':
            h = r.get('human_request') or {}
            return ' '.join(str(v) for v in h.values() if isinstance(v, str)) + ' ' + str(r.get('instruction') or '')
        return str(r.get('instruction') or '')
    put(f'NorthRot{key}Tasks', len(hit), f'{key}: tasks on these files (of {len(rows)})')
    put(f'NorthRot{key}Compass', sum(bool(WORDS.search(text(r))) for r in hit), f'{key}: of these, instructions with a compass word')
open(out_tex, 'w', encoding='utf-8').write('\n'.join(M) + '\n')
json.dump(V, open(out_json, 'w', encoding='utf-8'), indent=1)
print('\n'.join(M[2:]))
