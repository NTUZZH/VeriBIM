"""Macros of the ground-truth repair for the manuscript: writing/tables/macros_gtfix.tex.
Sources: gt_changes.csv (repaired ground truths), effect.csv (rescored rows), rerun_list.csv (re-run outputs),
merge_report.json (completion before and after per arm, canonical results after finalize_v4d.py)."""
import csv, json, collections
G = 'analysis/revision/ground_truth_repair'; OUT = 'writing/tables/macros_gtfix.tex'
M = []
def mac(n, v, note=''): M.append((n, str(v), note))
gt = list(csv.DictReader(open(f'{G}/gt_changes.csv')))
kinds = collections.Counter(r['edit_kind'] for r in gt)
mac('GtFixTasks', len(gt), 'benchmark tasks whose ground-truth model changed')
rehost = sum(v for k, v in kinds.items() if 'rehost' in k or 'move' in k); delete = sum(v for k, v in kinds.items() if 'delete' in k)
mac('GtFixRehost', rehost, 'of them re-hosting tasks (door or window moved to another wall)'); mac('GtFixDelete', delete, 'of them deletion tasks (dangling relationships)')
mac('GtFixOther', len(gt) - rehost - delete)
eff = list(csv.DictReader(open(f'{G}/effect.csv')))
changed = [r for r in eff if r['old_completed'] != r['new_completed']]
mac('GtFixRescoredRows', f'{len(eff):,}', 'archived outputs rescored against the repaired ground truths')
mac('GtFixRescoredChanged', len(changed), 'of them with a changed completion verdict')
rr = list(csv.DictReader(open(f'{G}/rerun_list.csv')))
import os
rd = list(csv.DictReader(open(f'{G}/rerun_list_delete_v2.csv'))) if os.path.exists(f'{G}/rerun_list_delete_v2.csv') else []
rd = [r for r in rd if r.get('geom_call_ran_clean', '1') not in ('0', '') and 'cpu_contended' not in r['run']]
mac('GtFixRerunRehostRows', len(rr), 'outputs that had used the defective re-hosting helper and were re-run')
mac('GtFixRerunDeleteRows', len(rd), 'outputs whose deletion helper ran on a repaired deletion task and were re-run')
mac('GtFixRerunRows', len(rr) + len(rd), 'outputs re-run in total')
mac('GtFixRerunArms', len({(r['run'], r['model']) for r in rr} | {(r['run'], r['model']) for r in rd}))
rep = json.load(open(f'{G}/merge_report.json'))['arms']
# v4e (deletion re-run) effect: completed_after is taken from the splice log where an arm was spliced
import os
if os.path.exists(f'{G}/delete_rerun/splice_v4e_log.json'):
    sp = json.load(open(f'{G}/delete_rerun/splice_v4e_log.json'))
    sp_arms = sp['arms'] if isinstance(sp, dict) and 'arms' in sp else sp
    by = {}
    for a in (sp_arms if isinstance(sp_arms, list) else sp_arms.values()):
        if isinstance(a, dict) and 'run' in a and 'model' in a: by[(a['run'], a['model'])] = a
    for a in rep:
        e = by.get((a['run'], a['model']))
        if e:
            for k in ('completed_after', 'completed_after_v4e', 'after', 'completed_new'):
                if k in e: a['completed_after'] = e[k]; break
    for (run, model), e in by.items():
        if not any(a['run'] == run and a['model'] == model for a in rep):
            n = e.get('n') or e.get('rows'); b = e.get('completed_before'); c = e.get('completed_after') or e.get('completed_after_v4e')
            if n is not None and b is not None and c is not None: rep.append({'run': run, 'model': model, 'n': n, 'completed_before': b, 'completed_after': c})
mac('GtFixArms', len(rep), 'arms with at least one affected row')
moved = [a for a in rep if a['completed_before'] != a['completed_after']]
mac('GtFixArmsMoved', len(moved), 'arms whose completion count changed')
mx = max(moved, key=lambda a: abs(a['completed_after'] - a['completed_before'])) if moved else None
if mx: mac('GtFixMaxDelta', mx['completed_after'] - mx['completed_before'], f"largest change: {mx['run']}/{mx['model']} of {mx['n']}")
def arm(run, model):
    a = [x for x in rep if x['run'] == run and x['model'] == model]; return a[0] if a else None
for run, model, nm in (('full_all', 'grpo_v10b_c10', 'OursFull'), ('local324_lib_all', 'grpo_v10b_c10', 'OursThreeTwentyFour'), ('local108_lib_all', 'grpo_v10b_c10', 'OursHundredEight'),
                       ('hosted108_informed_all', 'claude-sonnet-5-5', 'SonnetDocHundredEight'), ('hosted324_lib_all', 'claude-sonnet-5-5', 'SonnetLibThreeTwentyFour'), ('hosted216_lib_all', 'claude-sonnet-5-5', 'SonnetLibTwoSixteen')):
    a = arm(run, model)
    if a: mac(f'GtFix{nm}Before', f"{a['completed_before']:,}"); mac(f'GtFix{nm}After', f"{a['completed_after']:,}"); mac(f'GtFix{nm}N', f"{a['n']:,}")
with open(OUT, 'w') as f:
    f.write('% Generated by analysis/revision/ground_truth_repair/make_macros_gtfix.py.\n')
    for n, v, note in M: f.write(f'\\newcommand{{\\{n}}}{{{v}}}' + (f'  % {note}' if note else '') + '\n')
print(dict(kinds)); [print(f'{n:34s} {v:8s} {note}') for n, v, note in M]
