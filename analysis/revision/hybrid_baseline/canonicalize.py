"""Hybrid baseline, step 1: an untrained LLM rewrites a free-worded BIM edit request into the wording of the
task generator's templates (the template parser then executes it). Text only: the LLM sees the request and a
catalogue of generated example instructions, never the building model or the task's original wording.

  python canonicalize.py --backend {anthropic,local} --tasks in.jsonl --out out.jsonl [--subset ids.json] [--conc 4]

Output: the input task records with "instruction" replaced by the canonical sentence, plus
"request_text" (the request as given), "canon_raw" (the LLM's full reply) and "canon_recognised"
(whether the parser reads the canonical sentence). A record whose rewrite failed keeps the request text.
"""
import argparse, json, os, sys, time, re, concurrent.futures as cf
from pathlib import Path
ROOT = Path('.')
sys.path.insert(0, str(ROOT / 'code' / 'harness')); sys.path.insert(0, str(ROOT / 'analysis/revision/parser_baseline'))
from modifc_harness.client import ChatClient
import grammar

CAT = json.load(open(Path(__file__).resolve().parent / 'in' / 'catalogue.json'))
SHEET = open(Path(__file__).resolve().parent / 'in' / 'grammar_sheet.txt').read()
SYSTEM = (
    "You rewrite one BIM model edit request into the fixed wording of an edit-instruction template language. "
    "A deterministic program reads your sentence; it accepts only sentences written exactly like the examples below "
    "(same verbs, same clause order, same phrases for element references, storeys, directions, units and constraints). "
    "Rules: output exactly one sentence and nothing else, in the imperative form of the examples (no 'Please', no 'Can you', "
    "no preamble, no explanation). Keep every element name, GlobalId, number, unit and quoted string from the request verbatim; "
    "never invent an identifier or a value. Lengths are written in metres with the unit 'm' (convert mm only when the request gives mm). "
    "Choose the example sentence shape that states the same edit and fill it with the request's own values. If the request names its "
    "target in a way no example supports, still write the closest template sentence using the request's own words for the target.\n\n"
    "First the accepted phrase forms, then example instructions written in them.\n\n" + SHEET +
    "\n\nEXAMPLE INSTRUCTIONS (generated by the template system, one per sentence shape and target form):\n" + "\n".join("- " + e for e in CAT['examples']))
RETRY = ("The program could not read that sentence. Rewrite it so that it matches one accepted sentence shape and the accepted "
         "phrase forms exactly (verbs, clause order, element and storey reference forms, units, final period). Keep the request's "
         "values verbatim. Output exactly one sentence.")
MAX_ATTEMPTS = 3

class LocalClient:
    """vLLM chat completion with the Qwen3.5 thinking switch (chat_template_kwargs), temperature 0."""
    def __init__(self, base_url, model, thinking=False):
        self.base_url, self.model, self.thinking = base_url.rstrip('/'), model, thinking
    def chat(self, messages, max_tokens=None):
        import urllib.request, types
        payload = {'model': self.model, 'messages': messages, 'temperature': 0.0, 'top_p': 1.0, 'max_tokens': max_tokens or 1024,
                   'chat_template_kwargs': {'enable_thinking': bool(self.thinking)}}
        req = urllib.request.Request(self.base_url + '/chat/completions', data=json.dumps(payload).encode(), headers={'Content-Type': 'application/json'}, method='POST')
        with urllib.request.urlopen(req, timeout=1800) as r: body = json.loads(r.read())
        m = body['choices'][0]['message']
        return types.SimpleNamespace(content=m.get('content') or '', reasoning_content=m.get('reasoning_content') or '', finish_reason=body['choices'][0].get('finish_reason'))

def extract(text: str) -> str:
    t = re.sub(r"<think>.*?</think>", "", text or "", flags=re.S).strip()
    lines = [l.strip().strip('`').strip() for l in t.splitlines() if l.strip()]
    for l in reversed(lines):
        l = re.sub(r"^(Canonical( sentence)?|Output|Rewritten|Answer)\s*:\s*", "", l, flags=re.I).strip().strip('"')
        if re.search(r"[.?]$", l): return l
    return lines[-1] if lines else ""

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--backend', required=True, choices=['anthropic', 'local'])
    ap.add_argument('--tasks', required=True); ap.add_argument('--out', required=True)
    ap.add_argument('--subset', default=''); ap.add_argument('--conc', type=int, default=4)
    ap.add_argument('--max-tokens', type=int, default=4096)
    ap.add_argument('--thinking', default='off', choices=['off', 'on'], help='local backend: Qwen3.5 thinking mode')
    a = ap.parse_args()
    if a.backend == 'anthropic':
        key = os.environ['VERIBIM_API_KEY']   # exported by the launcher, as in the other commercial-model runs of this repository
        os.environ['VERIBIM_REQUEST_STYLE'] = 'anthropic_native'
        client = ChatClient('https://api.anthropic.com/v1', 'claude-sonnet-5-5', key, max_attempts=3)
    else:
        client = LocalClient('http://127.0.0.1:8000/v1', 'Qwen3.5-9B', thinking=(a.thinking == 'on'))
    recs = [json.loads(l) for l in open(a.tasks) if l.strip()]
    if a.subset:
        want = json.load(open(a.subset)); order = {t: i for i, t in enumerate(want)}
        recs = sorted((r for r in recs if r['task_id'] in order), key=lambda r: order[r['task_id']])
    out = Path(a.out); out.parent.mkdir(parents=True, exist_ok=True)
    done = {json.loads(l)['task_id'] for l in open(out)} if out.exists() else set()
    todo = [r for r in recs if r['task_id'] not in done]
    print(f'{len(recs)} tasks, {len(done)} done, {len(todo)} to rewrite; system prompt ~{len(SYSTEM)//4} tokens', flush=True)
    def one(r):
        req = r['instruction']; t0 = time.monotonic()
        msgs = [{'role': 'system', 'content': SYSTEM}, {'role': 'user', 'content': 'Request:\n' + req + '\n\nTemplate sentence:'}]
        raw = ''; err = None; canon = ''; it = {'recognised': False}; attempts = []
        for k in range(MAX_ATTEMPTS):
            try:
                resp = client.chat(msgs, max_tokens=a.max_tokens); raw = resp.content if hasattr(resp, 'content') else str(resp)
                if not isinstance(raw, str): raw = json.dumps(raw)
                err = None
            except Exception as e:
                raw, err = '', f'{type(e).__name__}: {e}'[:500]; break
            canon = extract(raw)
            it = grammar.parse(canon) if canon else {'recognised': False}
            attempts.append({'sentence': canon, 'recognised': bool(it.get('recognised'))})
            if it.get('recognised'): break
            msgs = msgs + [{'role': 'assistant', 'content': raw[-6000:]}, {'role': 'user', 'content': RETRY}]
        o = dict(r); o['request_text'] = req; o['instruction'] = canon or req
        o['canon_raw'] = raw[-4000:]; o['canon_raw_len'] = len(raw); o['canon_error'] = err; o['canon_recognised'] = bool(it.get('recognised'))
        o['canon_op'] = it.get('op'); o['canon_attempts'] = attempts; o['canon_seconds'] = round(time.monotonic() - t0, 1); o['canon_backend'] = a.backend
        return o
    n = 0; rec = 0
    with cf.ThreadPoolExecutor(a.conc) as ex, out.open('a', encoding='utf-8') as fh:
        for o in ex.map(one, todo):
            fh.write(json.dumps(o, ensure_ascii=False) + '\n'); fh.flush(); n += 1; rec += o['canon_recognised']
            if n % 10 == 0 or n == len(todo): print(f"{time.strftime('%T')} {n}/{len(todo)} recognised {rec}", flush=True)
if __name__ == '__main__': main()
