"""Macros and the supplementary table for the hybrid baseline (canonicalizer + template parser), from summary_hybrid.json
(summarize_hybrid.py). Writes writing/tables/macros_hybrid.tex and writing/tables/tab_hybrid_supp.tex."""
import json
from pathlib import Path
H = Path('analysis/revision/hybrid_baseline'); W = Path('writing/tables')
S = json.load(open(H / 'summary_hybrid.json'))
def rows(p): return {json.loads(l)['task_id']: json.loads(l) for l in open(p) if l.strip()}
def comp(r):
    sc = r.get('score') or {}; return all((sc.get(k) or 0) >= 0.9 for k in ('geometry', 'semantics', 'topology'))
def f3(x): return f'{x:.3f}'
def sgn(x): return ('$-$' if x < 0 else '') + f3(abs(x))
def pfmt(p): return '$<$0.001' if p < 0.001 else f'{p:.3f}'
M = []; names = {'rw': 'Rw', 'prac': 'Prac'}; cn = {'sonnet': 'Sonnet', 'local': 'Local'}
M.append(('HybRwN', '172')); M.append(('HybPracN', '200'))
for s in ('rw', 'prac'):
    for c in ('sonnet', 'local'):
        e = S[f'{s}_{c}']; k = f'Hyb{names[s]}{cn[c]}'
        hb = rows(H / f'scoring/{s}_{c}/per_task_parser.jsonl')
        wrong = sum(1 for r in hb.values() if r.get('program_written') and (r.get('commits') or 0) > 0 and not comp(r))
        fc = e['failure_classes']
        M += [(k + 'Recognised', str(e['recognised'])), (k + 'Done', str(e['completed'])), (k + 'Comp', f3(e['completion'])), (k + 'Mean', f3(e['mean'])),
              (k + 'MinusOurs', sgn(e['diff'])), (k + 'MinusOursLo', sgn(e['diff_lo'])), (k + 'MinusOursHi', sgn(e['diff_hi'])), (k + 'P', pfmt(e['mcnemar_p'])),
              (k + 'Both', str(e['model_completed'] - e['model_only'])), (k + 'Only', str(e['hybrid_only'])), (k + 'OursOnly', str(e['model_only'])),
              (k + 'Neither', str(e['n'] - (e['model_completed'] - e['model_only']) - e['hybrid_only'] - e['model_only'])),
              (k + 'WrongCommit', str(wrong)), (k + 'NotRecognised', str(fc.get('not recognised', 0))), (k + 'ProgramError', str(fc.get('program error', 0))), (k + 'WrongEdit', str(fc.get('wrong edit', 0))),
              (k + 'Attempts', f"{e['attempts_mean']:.2f}")]
    M.append((f'Hyb{names[s]}OursDone', str(S[f'{s}_sonnet']['model_completed']))); M.append((f'Hyb{names[s]}OursComp', f3(S[f'{s}_sonnet']['model_completion'])))
M.append(('HybCatalogueN', '266')); M.append(('HybMaxAttempts', 'three'))
with open(W / 'macros_hybrid.tex', 'w') as fh:
    fh.write('% GENERATED by analysis/revision/hybrid_baseline/make_macros_hybrid.py from summary_hybrid.json; do not edit by hand.\n')
    for k, v in M: fh.write(f'\\newcommand{{\\{k}}}{{{v}}}\n')
# table
L = [r'% GENERATED by analysis/revision/hybrid_baseline/make_macros_hybrid.py; do not edit by hand.',
     r'\begin{table}[pos=htbp]', r'\centering',
     "\\caption{Template parser with a language model that rewrites each request into the generator's wording, against \ModelName{} on the same tasks. Bold marks the higher completion in each row. The difference is the parser completion minus that of \ModelName{}, with a 95 percent bootstrap interval and an exact McNemar $p$.}",
     r'\label{tab:hybrid}', r'\scriptsize', r'\setlength{\tabcolsep}{2.1pt}', r'\begin{tabular}{@{}llrrccccrrrr@{}}', r'\toprule',
     r' & & & & \multicolumn{2}{c}{Completion} & & & \multicolumn{4}{c}{Tasks completed by} \\', r'\cmidrule(lr){5-6}\cmidrule(l){9-12}',
     r'Task set & Rewriting model & Tasks & Read & Parser & \ModelName{} & Difference [95\,\% CI] & $p$ & Both & Parser only & \ModelName{} only & Neither \\', r'\midrule']
setn = {'rw': 'Reworded tasks', 'prac': "Practitioners' requests"}; cnm = {'sonnet': 'Claude Sonnet 5.5', 'local': 'Qwen3.5-9B, untrained'}
for s in ('rw', 'prac'):
    for i, c in enumerate(('sonnet', 'local')):
        k = f'Hyb{names[s]}{cn[c]}'; e = S[f'{s}_{c}']
        a, b = f'\\{k}Comp{{}}', f'\\Hyb{names[s]}OursComp{{}}'
        if e['completion'] > e['model_completion']: a = r'\textbf{' + a + '}'
        elif e['completion'] < e['model_completion']: b = r'\textbf{' + b + '}'
        L.append(f"{setn[s] if i == 0 else ''} & {cnm[c]} & \\Hyb{names[s]}N{{}} & \\{k}Recognised{{}} & {a} & {b} & $\\{k}MinusOurs{{}}$ [$\\{k}MinusOursLo{{}}$, $\\{k}MinusOursHi{{}}$] & {pfmt(e['mcnemar_p'])} & \\{k}Both{{}} & \\{k}Only{{}} & \\{k}OursOnly{{}} & \\{k}Neither{{}} \\\\")
    if s == 'rw': L.append(r'\midrule')
L += [r'\bottomrule', r'\end{tabular}', r'\end{table}']
open(W / 'tab_hybrid_supp.tex', 'w').write('\n'.join(L) + '\n')
print(open(W / 'macros_hybrid.tex').read()); print(open(W / 'tab_hybrid_supp.tex').read())
