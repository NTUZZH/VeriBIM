#!/usr/bin/env python
"""Outcome classes of the proposed model's uncompleted practitioners' requests, and completion by whether the
candidate list holds every required element. Reads per-task rows only (no request text is read or written).

Usage: prac_failures.py PER_TASK_JSONL OUT_PREFIX [--label NAME]
Writes OUT_PREFIX.json and OUT_PREFIX.tex (macros \\PmPrac...). Inputs fixed below: the recall rows of the
candidate-element index on the 200 requests and the request-level reading (which requests do not identify
their target), kept as a CSV of task ids.
"""
import collections, csv, json, sys

ROOT = '.'
RECALL = f'{ROOT}/results/practitioner/candidate_list_recall.json'
READING = f'{ROOT}/results/practitioner/request_reading.csv'
AX = ('geometry', 'semantics', 'topology')


def comp(r):
    s = r.get('score') or {}
    return all((s.get(k) or 0) >= 0.9 for k in AX)


def outcome(r):
    s = r.get('score') or {}
    if not r.get('committed'):
        return 'NoCommitBudget' if r.get('stop_reason') == 'budget_exhausted' else (
            'NoCommitTruncated' if r.get('stop_reason') == 'output_truncated' else 'NoCommitOther')
    nm, nr = s.get('n_matched') or 0, s.get('n_reference') or 0
    if nm == 0:
        return 'NotMatched'
    if nm < nr:
        return 'PartlyMatched'
    return 'MatchedWrongEdit'


def main(argv):
    label = None
    if '--label' in argv:
        i = argv.index('--label'); label = argv[i + 1]; argv = argv[:i] + argv[i + 2:]
    src, prefix = argv
    rows = [json.loads(l) for l in open(src, encoding='utf-8') if l.strip()]
    assert len(rows) == 200 and all(r.get('score') is not None for r in rows), 'need 200 scored rows'
    rec = {r['task_id']: r for r in json.load(open(RECALL))['rows']}
    assert set(rec) == {r['task_id'] for r in rows}
    holds = {t: (v['worst'] is not None and v['worst'] <= 10) for t, v in rec.items()}
    reading = {r['task_id']: r for r in csv.DictReader(open(READING, encoding='utf-8'))}
    fail = [r for r in rows if not comp(r)]
    out = collections.Counter(outcome(r) for r in fail)
    by_op = collections.Counter((outcome(r), r.get('operation')) for r in fail)
    J = {'label': label, 'source': src, 'n': len(rows), 'done': sum(comp(r) for r in rows), 'failed': len(fail),
         'outcomes': dict(out), 'outcomes_by_operation': {f'{k[0]}/{k[1]}': v for k, v in sorted(by_op.items())},
         'list_holds_n': sum(holds.values()),
         'done_list_holds': sum(comp(r) for r in rows if holds[r['task_id']]),
         'done_list_misses': sum(comp(r) for r in rows if not holds[r['task_id']]),
         'failed_read': sum(1 for r in fail if r['task_id'] in reading),
         'failed_not_identifying': sum(1 for r in fail if reading.get(r['task_id'], {}).get('identifies_target') == '0'),
         'failed_unread': sorted(r['task_id'] for r in fail if r['task_id'] not in reading)}
    J['comp_list_holds'] = J['done_list_holds'] / J['list_holds_n']
    J['comp_list_misses'] = J['done_list_misses'] / (len(rows) - J['list_holds_n'])
    json.dump(J, open(prefix + '.json', 'w'), indent=1)
    M = [('PmPracFailTotal', len(fail)), ('PmPracFailNotMatched', out['NotMatched']),
         ('PmPracFailNotMatchedCreate', by_op[('NotMatched', 'create')]),
         ('PmPracFailNotMatchedOther', out['NotMatched'] - by_op[('NotMatched', 'create')]),
         ('PmPracFailPartly', out['PartlyMatched']), ('PmPracFailWrongEdit', out['MatchedWrongEdit']),
         ('PmPracFailBudget', out['NoCommitBudget']), ('PmPracFailTruncated', out['NoCommitTruncated']),
         ('PmPracFailNoCommit', out['NoCommitBudget'] + out['NoCommitTruncated'] + out['NoCommitOther']),
         ('PmPracFailNotIdentifying', J['failed_not_identifying']),
         ('PmPracListHoldsN', J['list_holds_n']), ('PmPracListMissesN', len(rows) - J['list_holds_n']),
         ('PmPracDoneListHolds', J['done_list_holds']), ('PmPracCompListHolds', f"{J['comp_list_holds']:.3f}"),
         ('PmPracDoneListMisses', J['done_list_misses']), ('PmPracCompListMisses', f"{J['comp_list_misses']:.3f}")]
    with open(prefix + '.tex', 'w', encoding='utf-8') as f:
        f.write('% Generated by analysis/prac_failures.py from the per-task rows of the proposed model on the practitioners\' requests.\n')
        for k, v in M:
            f.write(f'\\newcommand{{\\{k}}}{{{v}}}\n')
    print(json.dumps({k: v for k, v in J.items() if k != 'source'}, indent=1))


if __name__ == '__main__':
    main(sys.argv[1:])
